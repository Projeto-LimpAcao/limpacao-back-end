
CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(255) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    senha       VARCHAR(255) NOT NULL,
    paleta_tema VARCHAR(20)  NOT NULL DEFAULT 'verde',
    modo_escuro BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em   TIMESTAMP(6),
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE relatorios (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                   VARCHAR(255) NOT NULL,
    localizacao              VARCHAR(255) NOT NULL,
    cep                      VARCHAR(10),
    rua                      VARCHAR(255),
    cidade                   VARCHAR(255),
    estado                   VARCHAR(100),
    numero                   VARCHAR(50),
    latitude                 DOUBLE PRECISION,
    longitude                DOUBLE PRECISION,
    urgencia                 VARCHAR(20)  NOT NULL,
    status                   VARCHAR(30)  NOT NULL,
    data                     DATE         NOT NULL,
    imagem                   TEXT,
    descricao                TEXT         NOT NULL,
    autor                    VARCHAR(255) NOT NULL,
    participantes            INTEGER      NOT NULL DEFAULT 0,
    ajudantes                INTEGER      NOT NULL DEFAULT 0,
    multirao                 BOOLEAN      NOT NULL DEFAULT FALSE,
    status_anterior          VARCHAR(30),
    imagem_conclusao         TEXT,
    justificativa_reabertura TEXT,
    usuario_id               BIGINT,
    criado_em                TIMESTAMP(6),
    atualizado_em            TIMESTAMP(6)
);

CREATE INDEX idx_relatorios_usuario ON relatorios (usuario_id);
CREATE INDEX idx_relatorios_status  ON relatorios (status);

CREATE TABLE ofertas_ajuda (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id BIGINT       NOT NULL,
    usuario_id   BIGINT,
    nome         VARCHAR(255) NOT NULL,
    telefone     VARCHAR(50)  NOT NULL,
    mensagem     TEXT,
    criado_em    TIMESTAMP(6),
    CONSTRAINT uk_ofertas_ajuda_relatorio_usuario UNIQUE (relatorio_id, usuario_id)
);

CREATE INDEX idx_ofertas_ajuda_usuario ON ofertas_ajuda (usuario_id);

CREATE TABLE participacoes_relatorio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id      BIGINT      NOT NULL,
    usuario_id        BIGINT      NOT NULL,
    tipo_participacao VARCHAR(30) NOT NULL,
    criado_em         TIMESTAMP(6),
    CONSTRAINT uk_participacoes_relatorio_usuario_tipo UNIQUE (relatorio_id, usuario_id, tipo_participacao)
);

CREATE INDEX idx_participacoes_usuario ON participacoes_relatorio (usuario_id);

CREATE TABLE mensagens_chat (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    relatorio_id     BIGINT       NOT NULL,
    autor            VARCHAR(255) NOT NULL,
    texto            TEXT         NOT NULL,
    resposta_a_id    BIGINT,
    resposta_a_autor VARCHAR(255),
    resposta_a_texto TEXT,
    criado_em        TIMESTAMP(6)
);

CREATE INDEX idx_mensagens_chat_relatorio ON mensagens_chat (relatorio_id);

CREATE TABLE mensagens_oferta_ajuda (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id  BIGINT        NOT NULL,
    usuario_id BIGINT        NOT NULL,
    texto      VARCHAR(4000) NOT NULL,
    criado_em  TIMESTAMP(6)  NOT NULL
);

CREATE INDEX idx_mensagens_oferta_ajuda_oferta ON mensagens_oferta_ajuda (oferta_id);

CREATE TABLE leituras_mensagem_oferta_ajuda (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id          BIGINT       NOT NULL,
    usuario_id         BIGINT       NOT NULL,
    lida_em            TIMESTAMP(6) NOT NULL,
    ultima_mensagem_id BIGINT,
    CONSTRAINT uk_leitura_oferta_usuario UNIQUE (oferta_id, usuario_id)
);

CREATE TABLE recuperacoes_senha (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL,
    codigo_hash VARCHAR(100) NOT NULL,
    expira_em   TIMESTAMP(6) NOT NULL,
    tentativas  INTEGER      NOT NULL DEFAULT 0,
    utilizado   BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em   TIMESTAMP(6)
);

CREATE INDEX idx_recuperacoes_senha_usuario ON recuperacoes_senha (usuario_id);
